from flask import Flask, request, abort, jsonify
from cfenv import AppEnv
from sap import xssec
from hdbcli import dbapi

app = Flask(__name__)
env = AppEnv()
uaa = env.get_service(name='my-python-xsuaa').credentials
db = env.get_service(name='my-python-hana').credentials


# ---------- Security ----------
def get_context():
    """Return the user's security context, or refuse with 401."""
    auth = request.headers.get('Authorization', '')
    if not auth.startswith('Bearer '):
        abort(401)
    try:
        return xssec.create_security_context(auth[7:], uaa)
    except Exception:
        abort(401)

def user_scopes(ctx):
    return [s for s in ('Display', 'Admin') if ctx.check_local_scope(s)]

def require(scope):
    """Check the login token and the scope; return the security context."""
    ctx = get_context()
    if not ctx.check_local_scope(scope):
        abort(403)
    return ctx


# ---------- Database ----------
_table_ready = False

def get_db():
    """Open a connection to the app's SAP HANA Cloud schema."""
    params = dict(address=db['host'], port=int(db['port']),
                  user=db['user'], password=db['password'],
                  currentSchema=db['schema'],
                  encrypt=True, sslValidateCertificate=True)
    if db.get('certificate'):
        params['sslTrustStore'] = db['certificate']
    return dbapi.connect(**params)

def ensure_table(cur):
    """Create the ITEMS table the first time it is needed."""
    global _table_ready
    if _table_ready:
        return
    cur.execute("SELECT COUNT(*) FROM TABLES "
                "WHERE SCHEMA_NAME = CURRENT_SCHEMA AND TABLE_NAME = 'ITEMS'")
    if cur.fetchone()[0] == 0:
        cur.execute("""
            CREATE COLUMN TABLE ITEMS (
                ID         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                ITEM_TEXT  NVARCHAR(200) NOT NULL,
                CREATED_BY NVARCHAR(256),
                CREATED_AT TIMESTAMP DEFAULT CURRENT_UTCTIMESTAMP
            )""")
    _table_ready = True


# ---------- Routes ----------
@app.route('/')
def hello():
    ctx = require('Display')
    return (f"Hello {ctx.get_given_name()} ({ctx.get_email()})! "
            f"Your permissions: {', '.join(user_scopes(ctx))}.")

@app.route('/me')
def me():
    """Who is logged in and what they may do, as JSON for the web page."""
    ctx = require('Display')
    return jsonify(name=ctx.get_given_name(),
                   email=ctx.get_email(),
                   scopes=user_scopes(ctx))

@app.route('/admin')
def admin():
    require('Admin')
    return "Admin area: only users with the Administrator role can see this page."

@app.route('/items', methods=['GET'])
def list_items():
    """Viewers and admins can read the list."""
    require('Display')
    conn = get_db()
    try:
        cur = conn.cursor()
        ensure_table(cur)
        cur.execute("SELECT ID, ITEM_TEXT, CREATED_BY, CREATED_AT "
                    "FROM ITEMS ORDER BY ID DESC")
        rows = [dict(id=r[0], text=r[1], created_by=r[2],
                     created_at=r[3].isoformat() if r[3] else None)
                for r in cur.fetchall()]
    finally:
        conn.close()
    return jsonify(rows)

@app.route('/items', methods=['POST'])
def add_item():
    """Only admins can add items."""
    ctx = require('Admin')
    text = ((request.get_json(silent=True) or {}).get('text') or '').strip()
    if not 1 <= len(text) <= 200:
        abort(400)
    conn = get_db()
    try:
        cur = conn.cursor()
        ensure_table(cur)
        cur.execute("INSERT INTO ITEMS (ITEM_TEXT, CREATED_BY) VALUES (?, ?)",
                    (text, ctx.get_email()))
        conn.commit()
    finally:
        conn.close()
    return jsonify(status='created'), 201
